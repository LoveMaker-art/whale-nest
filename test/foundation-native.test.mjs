import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fixtureDirectory, boot, input, owners } from './host-helper.mjs';
import { bridgeDirectory, bootBridge } from './bridge-helper.mjs';

const call = (name, args) => 'FOUNDATION_TOOL ' + JSON.stringify({ name, args });
const trace = async directory => (await readFile(join(directory.root, 'trace.jsonl'), 'utf8')).trim().split('\n').map(JSON.parse);

test('persona management runs through native tools and changes the next model request without losing state', { timeout: 60000 }, async t => {
  const directory = await fixtureDirectory();
  let host = await boot(directory);
  t.after(() => host.close());
  assert.equal((await host.request('status')).persona.currentId, 'dafeiyu-original');
  await host.request('receive', { input: input('create-persona', call('companion_persona', { action: 'create', id: 'blue', name: '小蓝', body: 'PERSONA_FIXTURE_ACTIVE 你是小蓝，说话简短。' })) });
  const beforeUse = (await trace(directory)).length;
  await host.request('receive', { input: input('use-persona', call('companion_persona', { action: 'use', id: 'blue' })) });
  assert.equal((await host.request('status')).persona.currentId, 'blue');
  const useRequests = (await trace(directory)).slice(beforeUse);
  assert.ok(useRequests.length >= 2, 'The real tool loop completes');
  assert.ok(useRequests.every(r => !JSON.stringify(r.messages.filter(m => m.role === 'system')).includes('PERSONA_FIXTURE_ACTIVE')),
    'The switching tool does not change the current turn system prompt');
  const beforeNext = (await trace(directory)).length;
  await host.request('receive', { input: input('new-persona', '现在继续聊天') });
  const next = (await trace(directory)).slice(beforeNext);
  assert.ok(next.some(r => JSON.stringify(r.messages.filter(m => m.role === 'system')).includes('PERSONA_FIXTURE_ACTIVE')));
  assert.ok(next.every(r => !JSON.stringify(r.messages.filter(m => m.role === 'system')).includes('你本来是 DeepSeek')),
    'The original persona is replaced in the actual system prompt');
  const attempts = ['delete-current', 'stranger-change', 'schedule-change'];
  await host.request('receive', { input: input(attempts[0], call('companion_persona', { action: 'delete', id: 'blue' })) });
  await host.request('receive', { input: input(attempts[1], call('companion_persona', { action: 'use', id: 'dafeiyu-original' }), { sender: 'bob', conversation: 'dm-bob' }) });
  await host.request('receive', { input: { ...input(attempts[2], call('companion_persona', { action: 'use', id: 'dafeiyu-original' })), source: 'schedule' } });
  assert.equal((await host.request('status')).persona.currentId, 'blue');
  await host.close(); host = await boot(directory);
  assert.equal((await host.request('status')).persona.currentId, 'blue');
  const qq = { ...owners[1], kind: 'private', conversation: 'qq-owner' };
  await host.request('receive', { input: input('qq-persona', '另一来源也使用同一个伙伴', qq) });
  await host.request('receive', { input: input('restore-persona', call('companion_persona', { action: 'use', id: 'dafeiyu-original' })) });
  assert.equal((await host.request('status')).persona.currentId, 'dafeiyu-original');
});

test('native memory consolidation reads admitted user text, budgets direct retries and preserves management/mood state', { timeout: 60000 }, async t => {
  const directory = await fixtureDirectory();
  directory.options.memory = { automatic: true };
  directory.options.activities = { maxDailyBackgroundModelCalls: 2 };
  await writeFile(directory.configPath, JSON.stringify(directory.options));
  let host = await boot(directory);
  t.after(() => host.close());
  await host.request('background.configure', { patch: { awakeFrom: 0, awakeTo: 24 } });
  await host.request('receive', { input: input('memory-fact', '我最喜欢茉莉花茶 MEMORY_AUTO_JASMINE MEMORY_FORCE_RETRY，谢谢你，抱抱') });
  const moodFile = join(directory.options.dataDir, 'aurabot/mood.json');
  const moodBefore = JSON.parse(await readFile(moodFile, 'utf8'));
  assert.ok(moodBefore.history.length > 0);
  await host.request('receive', { input: input('maintenance-input', '运维自测 讨厌滚') });
  await host.request('receive', { input: { ...input('schedule-input', '讨厌滚'), source: 'schedule' } });
  assert.deepEqual(JSON.parse(await readFile(moodFile, 'utf8')), moodBefore, 'Self-tests and scheduler do not change mood');
  const before = await trace(directory);
  const result = await host.request('memory.consolidate');
  const items = await host.request('memory.list');
  const item = items.find(m => m.text.includes('MEMORY_AUTO_JASMINE'));
  assert.ok(item, JSON.stringify({ result, items }));
  const after = await trace(directory);
  const direct = after.slice(before.length).filter(r => r.messages.some(m => m.source?.kind === 'plugin'));
  assert.equal(direct.length, 2, 'Each original retry is a separately budgeted real stream');
  const status = (await host.request('status')).memory;
  assert.equal(status.usage.modelRequests, 2);
  assert.equal(status.blockedReason, 'daily-model-limit');
  const projected = (await readFile(join(directory.options.dataDir, 'aurabot/chatlog', status.historyDays[0] + '.jsonl'), 'utf8')).trim().split('\n').map(JSON.parse);
  assert.equal(projected.length, 1, 'Only genuine owner input is included');
  assert.ok(projected[0].sourceId);
  await host.request('receive', { input: input('recall-auto', '请回想我的茉莉花茶偏好') });
  assert.ok(JSON.stringify((await trace(directory)).at(-1)).includes('MEMORY_AUTO_JASMINE'));
  await host.request('receive', { input: input('correct-auto', call('companion_memory', { action: 'update', id: item.id, text: '主人现在喜欢乌龙茶 MEMORY_CORRECTED_OOLONG' })) });
  assert.equal((await host.request('memory.list')).find(m => m.id === item.id).text, '主人现在喜欢乌龙茶 MEMORY_CORRECTED_OOLONG');
  await host.request('receive', { input: input('stranger-memory', call('companion_memory', { action: 'delete', id: item.id }), { sender: 'bob', conversation: 'dm-bob' }) });
  assert.ok((await host.request('memory.list')).some(m => m.id === item.id));
  assert.ok(!JSON.stringify((await trace(directory)).at(-1)).includes('MEMORY_CORRECTED_OOLONG'), 'Private memory is absent from the other participant request');
  await host.close(); host = await boot(directory);
  assert.equal((await host.request('status')).memory.usage.modelRequests, 2);
  assert.ok((await host.request('memory.list')).some(m => m.text.includes('MEMORY_CORRECTED_OOLONG')));
  assert.deepEqual(JSON.parse(await readFile(moodFile, 'utf8')).history, moodBefore.history);
  await host.request('receive', { input: input('delete-auto', call('companion_memory', { action: 'delete', id: item.id })) });
  assert.ok(!(await host.request('memory.list')).some(m => m.id === item.id));
  const blocked = await host.request('memory.consolidate');
  assert.equal(blocked.reason, 'daily-model-limit');
  await host.request('background.configure', { patch: { paused: true } });
  assert.equal((await host.request('memory.consolidate')).reason, 'paused');
});

test('native memory with zero budget makes no direct model call and remains usable for normal chat', { timeout: 30000 }, async t => {
  const directory = await fixtureDirectory();
  directory.options.memory = { automatic: true };
  await writeFile(directory.configPath, JSON.stringify(directory.options));
  const host = await boot(directory); t.after(() => host.close());
  await host.request('background.configure', { patch: { awakeFrom: 0, awakeTo: 24 } });
  await host.request('receive', { input: input('zero-budget-memory', '我喜欢茉莉花茶 MEMORY_AUTO_JASMINE') });
  const before = (await trace(directory)).length;
  assert.equal((await host.request('memory.consolidate')).reason, 'background-model-disabled');
  assert.equal((await trace(directory)).length, before);
  assert.equal((await host.request('receive', { input: input('normal-after-zero', '继续聊天') })).state, 'completed');
});

test('existing Core bridge admits memory exactly once and exposes the new owner tools without a second sender', { timeout: 60000 }, async t => {
  const directory = await bridgeDirectory();
  directory.options.memory = { automatic: true };
  directory.options.activities = { maxDailyBackgroundModelCalls: 2 };
  await writeFile(directory.configPath, JSON.stringify(directory.options));
  const bridge = await bootBridge(directory); t.after(() => bridge.close());
  await bridge.control('policyConfigure', { awakeFrom: 0, awakeTo: 24 });
  const sessionId = 'foundation-original-core';
  await bridge.request('create', { sessionId, cwd: directory.root, whalenestChatId: 'dm-alice', model: directory.options.model });
  const text = '<clawchat_turn_context>\n{"displayName":"可爱"}\n</clawchat_turn_context>\n我最喜欢茉莉花茶 MEMORY_AUTO_JASMINE MEMORY_FORCE_RETRY，谢谢';
  const accepted = await bridge.turn(sessionId, 'bridge-memory-fact', text);
  const duplicate = await bridge.request('prompt', { sessionId, inputId: 'bridge-memory-fact', text });
  assert.equal(duplicate.messageId, accepted.messageId);
  await bridge.control('memoryConsolidate');
  const status = await bridge.control('memoryState');
  assert.ok(status.items.some(m => m.text.includes('MEMORY_AUTO_JASMINE')));
  assert.equal(status.usage.modelRequests, 2);
  const records = (await readFile(join(directory.options.dataDir, 'aurabot/chatlog', status.historyDays[0] + '.jsonl'), 'utf8')).trim().split('\n').map(JSON.parse);
  assert.equal(records.length, 1);
  assert.ok(!records[0].text.includes('clawchat_turn_context'));
  const mood = JSON.parse(await readFile(join(directory.options.dataDir, 'aurabot/mood.json'), 'utf8'));
  assert.equal(mood.history[0].to - mood.history[0].from, 9, 'Transport display names must not add emotion keywords');
  assert.ok(!mood.history[0].reason.includes('clawchat_turn_context'));
  const inspect = await bridge.request('companionStatus', { sessionId });
  assert.ok(inspect.tools.includes('companion_persona'));
  assert.ok(inspect.tools.includes('companion_memory'));
  assert.equal((await bridge.control('outbox')).length, 0, 'Core still owns foreground reply delivery');
});
